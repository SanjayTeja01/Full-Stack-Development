import {
  collection,
  doc,
  limit,
  limitToLast,
  onSnapshot,
  orderBy,
  query,
  serverTimestamp,
  updateDoc,
  where,
} from "firebase/firestore";
import { firebase } from "@/lib/firebase/client";
import { call } from "@/lib/firebase/callable";
import type { Conversation, Message, Offer } from "@shared/types";

type OnError = (e: Error) => void;

export function subscribeConversations(uid: string, cb: (c: Conversation[]) => void, onError: OnError) {
  const q = query(collection(firebase().db, "conversations"), where("participantIds", "array-contains", uid), orderBy("updatedAt", "desc"), limit(100));
  return onSnapshot(q, (s) => cb(s.docs.map((d) => d.data() as Conversation)), onError);
}

export function subscribeConversation(id: string, cb: (c: Conversation | null) => void, onError: OnError) {
  return onSnapshot(doc(firebase().db, "conversations", id), (s) => cb(s.exists() ? (s.data() as Conversation) : null), onError);
}

export function subscribeMessages(conversationId: string, cb: (m: Message[]) => void, onError: OnError, max = 200) {
  const q = query(collection(firebase().db, "conversations", conversationId, "messages"), orderBy("createdAt", "asc"), limitToLast(max));
  return onSnapshot(q, { includeMetadataChanges: false }, (s) => cb(s.docs.map((d) => d.data() as Message)), onError);
}

/** Offers in a conversation. The participant filter is required so Security Rules can authorise the query. */
export function subscribeConversationOffers(conversationId: string, uid: string, role: "buyer" | "farmer", cb: (o: Offer[]) => void, onError: OnError) {
  const q = query(
    collection(firebase().db, "offers"),
    where(role === "buyer" ? "buyerId" : "farmerId", "==", uid),
    where("conversationId", "==", conversationId),
    orderBy("createdAt", "asc"),
  );
  return onSnapshot(q, (s) => cb(s.docs.map((d) => d.data() as Offer)), onError);
}

export function subscribeMyOffers(uid: string, role: "buyer" | "farmer", cb: (o: Offer[]) => void, onError: OnError) {
  const q = query(collection(firebase().db, "offers"), where(role === "buyer" ? "buyerId" : "farmerId", "==", uid), orderBy("createdAt", "desc"), limit(300));
  return onSnapshot(q, (s) => cb(s.docs.map((d) => d.data() as Offer)), onError);
}

/**
 * Sends a text message through the server, which writes it with the conversation preview and unread
 * counts and notifies the other participant. The id is generated by the caller and reused on retry,
 * so a resend after a network failure can never create a duplicate.
 */
export function sendMessage(conversationId: string, messageId: string, text: string) {
  return call<{ conversationId: string; messageId: string; text: string }, { messageId: string; duplicate: boolean }>("sendMessage", {
    conversationId,
    messageId,
    text,
  });
}

export function markConversationRead(conversationId: string, uid: string) {
  return updateDoc(doc(firebase().db, "conversations", conversationId), {
    [`unreadCounts.${uid}`]: 0,
    [`lastReadAt.${uid}`]: serverTimestamp(),
  });
}

export function newMessageId(): string {
  return `m_${Date.now().toString(36)}_${crypto.randomUUID().slice(0, 8)}`;
}
